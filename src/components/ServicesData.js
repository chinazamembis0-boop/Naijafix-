export const allServices = serviceCategories.flatMap((category) => category.services)

export function getServiceCategory(service) {
  if (!service) return null
  const serviceId = String(service.id || '').toLowerCase()
  const serviceName = String(service.name || '').toLowerCase()
  const serviceCategory = String(service.category || '').toLowerCase()

  for (const category of serviceCategories) {
    for (const s of category.services) {
      if (
        String(s.id).toLowerCase() === serviceId ||
        String(s.name).toLowerCase() === serviceName ||
        String(s.category).toLowerCase() === serviceCategory
      ) {
        return category
      }
    }
  }
  return null
}

export function getServiceById(id) {
  const normalizedId = String(id || '').toLowerCase()
  return allServices.find((s) => String(s.id).toLowerCase() === normalizedId)
}

export default serviceCategories

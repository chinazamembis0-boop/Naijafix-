-- H. Storage bucket for booking photos (private)
-- ============================================================
insert into storage.buckets (id, name, public)
values ('booking-photos', 'booking-photos', false)
on conflict (id) do nothing;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Booking participants can upload booking photos'
  ) then
    create policy "Booking participants can upload booking photos"
      on storage.objects for insert to authenticated
      with check (
        bucket_id = 'booking-photos'
        and exists (
          select 1 from public.booking_photos bp
          where bp.file_path = storage.foldername(name) || '/' || storage.filename(name)
            and bp.uploader_user_id = auth.uid()
        )
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Booking participants can view booking photos'
  ) then
    create policy "Booking participants can view booking photos"
      on storage.objects for select to authenticated
      using (
        bucket_id = 'booking-photos'
        and exists (
          select 1 from public.booking_photos bp
          where bp.file_path = storage.foldername(name) || '/' || storage.filename(name)
            and exists (
              select 1 from public.bookings b
              where b.id = bp.booking_id
                and (b.customer_user_id = auth.uid() or b.provider_user_id = auth.uid())
            )
        )
      );
  end if;
end
$$;


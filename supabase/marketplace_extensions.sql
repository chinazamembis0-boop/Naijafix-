  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'quotes'
      and policyname = 'Providers can update their own quotes'
  ) then
    create policy "Providers can update their own quotes"
      on public.quotes
      for update to authenticated
      using (provider_user_id = auth.uid())
      with check (provider_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'quotes'
      and policyname = 'Customers can accept or decline quotes'
  ) then
    create policy "Customers can accept or decline quotes"
      on public.quotes
      for update to authenticated
      using (
        exists (
          select 1 from public.bookings b
          where b.id = booking_id and b.customer_user_id = auth.uid()
        )
      )
      with check (
        exists (
          select 1 from public.bookings b
          where b.id = booking_id and b.customer_user_id = auth.uid()
        )

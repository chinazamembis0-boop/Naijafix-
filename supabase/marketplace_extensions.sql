-- ============================================================
-- A. Reviews / Ratings
-- ============================================================
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  booking_id bigint not null unique,
  customer_user_id uuid not null,
  provider_user_id uuid not null,
  rating integer not null check (rating >= 1 and rating <= 5),
  comment text,
  provider_response text,
  responded_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.reviews enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'reviews'
      and policyname = 'Customers can view reviews'
  ) then
    create policy "Customers can view reviews"
      on public.reviews
      for select to authenticated
      using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'reviews'
      and policyname = 'Customers can insert their own reviews'
  ) then
    create policy "Customers can insert their own reviews"
      on public.reviews
      for insert to authenticated
      with check (customer_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'reviews'
      and policyname = 'Customers can update their own reviews'
  ) then
    create policy "Customers can update their own reviews"
      on public.reviews
      for update to authenticated
      using (customer_user_id = auth.uid())
      with check (customer_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'reviews'
      and policyname = 'Providers can respond to their reviews'
  ) then
    create policy "Providers can respond to their reviews"
      on public.reviews
      for update to authenticated
      using (provider_user_id = auth.uid())
      with check (provider_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'reviews'
      and policyname = 'Admins can manage reviews'
  ) then
    create policy "Admins can manage reviews"
      on public.reviews
      for all to authenticated
      using (
        exists (
          select 1 from public.profiles p
          where p.user_id = auth.uid() and p.role = 'admin'
        )
      )
      with check (
        exists (
          select 1 from public.profiles p
          where p.user_id = auth.uid() and p.role = 'admin'
        )
      );
  end if;
end
$$;

create index if not exists idx_reviews_provider
  on public.reviews (provider_user_id, created_at desc);

create index if not exists idx_reviews_booking
  on public.reviews (booking_id);


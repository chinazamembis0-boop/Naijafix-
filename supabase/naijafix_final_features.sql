-- E. Storage buckets. Profile/work-sample images are private by default;
-- clients should use signed URLs. Verification documents are always private.
insert into storage.buckets (id, name, public)
values
  ('profile-photos', 'profile-photos', false),
  ('provider-work-samples', 'provider-work-samples', false),
  ('provider-verification-documents', 'provider-verification-documents', false)
on conflict (id) do nothing;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Users can upload their own profile photos'
  ) then
    create policy "Users can upload their own profile photos"
      on storage.objects for insert to authenticated
      with check (
        bucket_id = 'profile-photos'
        and (storage.foldername(name))[1] = auth.uid()::text
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Users can manage their own profile photos'
  ) then
    create policy "Users can manage their own profile photos"
      on storage.objects for all to authenticated
      using (
        bucket_id = 'profile-photos'
        and (storage.foldername(name))[1] = auth.uid()::text
      )
      with check (
        bucket_id = 'profile-photos'
        and (storage.foldername(name))[1] = auth.uid()::text
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Providers can manage their own work sample files'
  ) then
    create policy "Providers can manage their own work sample files"
      on storage.objects for all to authenticated
      using (
        bucket_id = 'provider-work-samples'
        and (storage.foldername(name))[1] = auth.uid()::text
      )
      with check (
        bucket_id = 'provider-work-samples'
        and (storage.foldername(name))[1] = auth.uid()::text
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Providers can manage their own verification files'
  ) then
    create policy "Providers can manage their own verification files"
      on storage.objects for all to authenticated
      using (
        bucket_id = 'provider-verification-documents'
        and (storage.foldername(name))[1] = auth.uid()::text
      )
      with check (
        bucket_id = 'provider-verification-documents'
        and (storage.foldername(name))[1] = auth.uid()::text
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Admins can review verification files'
  ) then
    create policy "Admins can review verification files"
      on storage.objects for select to authenticated
      using (
        bucket_id = 'provider-verification-documents'
        and exists (
          select 1 from public.profiles p
          where p.user_id = auth.uid() and p.role = 'admin'
        )
      );
  end if;
end
$$;


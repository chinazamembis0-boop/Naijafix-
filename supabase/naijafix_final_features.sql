-- NaijaFix final feature foundation
-- Run in Supabase SQL Editor. This migration does not delete data or replace existing policies.

-- A. Existing profile/provider photo fields
alter table public.profiles
  add column if not exists avatar_url text;

alter table public.providers
  add column if not exists avatar_url text;

-- B. Provider work samples
create table if not exists public.provider_work_samples (
  id bigint generated by default as identity primary key,
  provider_user_id uuid not null,
  image_url text not null,
  caption text,
  created_at timestamptz not null default now()
);

alter table public.provider_work_samples enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'provider_work_samples'
      and policyname = 'Authenticated users can view provider work samples'
  ) then
    create policy "Authenticated users can view provider work samples"
      on public.provider_work_samples
      for select to authenticated
      using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'provider_work_samples'
      and policyname = 'Providers can insert their own work samples'
  ) then
    create policy "Providers can insert their own work samples"
      on public.provider_work_samples
      for insert to authenticated
      with check (provider_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'provider_work_samples'
      and policyname = 'Providers can update their own work samples'
  ) then
    create policy "Providers can update their own work samples"
      on public.provider_work_samples
      for update to authenticated
      using (provider_user_id = auth.uid())
      with check (provider_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'provider_work_samples'
      and policyname = 'Providers can delete their own work samples'
  ) then
    create policy "Providers can delete their own work samples"
      on public.provider_work_samples
      for delete to authenticated
      using (provider_user_id = auth.uid());
  end if;
end
$$;

-- C. Private provider verification records and documents
create table if not exists public.provider_verifications (
  id bigint generated by default as identity primary key,
  provider_user_id uuid not null,
  id_document_url text,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid,
  rejection_reason text
);

alter table public.provider_verifications enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'provider_verifications'
      and policyname = 'Providers can view their own verification'
  ) then
    create policy "Providers can view their own verification"
      on public.provider_verifications
      for select to authenticated
      using (provider_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'provider_verifications'
      and policyname = 'Providers can submit their own verification'
  ) then
    create policy "Providers can submit their own verification"
      on public.provider_verifications
      for insert to authenticated
      with check (provider_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'provider_verifications'
      and policyname = 'Admins can review provider verification'
  ) then
    create policy "Admins can review provider verification"
      on public.provider_verifications
      for all to authenticated
      using (exists (
        select 1 from public.profiles p
        where p.user_id = auth.uid() and p.role = 'admin'
      ))
      with check (exists (
        select 1 from public.profiles p
        where p.user_id = auth.uid() and p.role = 'admin'
      ));
  end if;
end
$$;

-- D. Complaints and reports
create table if not exists public.support_reports (

-- NaijaFix: Restaurants, menu categories, and menu items
-- Idempotent: safe to run multiple times.
-- Preserves existing data.

-- ============================================================
-- A. Restaurants table
-- ============================================================
create table if not exists public.restaurants (
  id bigint generated by default as identity primary key,
  owner_user_id uuid not null,
  name text not null,
  description text,
  phone text,
  email text,
  address text,
  city text,
  latitude numeric(10, 7),
  longitude numeric(10, 7),
  logo_url text,
  cover_image_url text,
  cuisine text,
  delivery_fee numeric(10, 2) not null default 0,
  estimated_delivery_minutes integer not null default 30,
  rating numeric(3, 2) not null default 0,
  is_open boolean not null default true,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.restaurants enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'restaurants'
      and policyname = 'Anyone can view active restaurants'
  ) then
    create policy "Anyone can view active restaurants"
      on public.restaurants
      for select to authenticated
      using (is_active = true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'restaurants'
      and policyname = 'Restaurant owners can manage their own restaurant'
  ) then
    create policy "Restaurant owners can manage their own restaurant"
      on public.restaurants
      for all to authenticated
      using (owner_user_id = auth.uid())
      with check (owner_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'restaurants'
      and policyname = 'Admins can manage all restaurants'
  ) then
    create policy "Admins can manage all restaurants"
      on public.restaurants
      for all to authenticated
      using (
        exists (
          select 1 from public.profiles p
          where p.user_id = auth.uid() and p.role = 'admin'
        )
      )
      with check (
        exists (
          select 1 from public.profiles p
          where p.user_id = auth.uid() and p.role = 'admin'
        )
      );
  end if;
end
$$;

create index if not exists idx_restaurants_owner
  on public.restaurants (owner_user_id);

create index if not exists idx_restaurants_city
  on public.restaurants (city);

create index if not exists idx_restaurants_cuisine
  on public.restaurants (cuisine);

create index if not exists idx_restaurants_active
  on public.restaurants (is_active, is_open);

grant select, insert, update, delete on public.restaurants to authenticated;

-- ============================================================
-- B. Restaurant menu categories
-- ============================================================
create table if not exists public.restaurant_menu_categories (
  id bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  name text not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.restaurant_menu_categories enable row level security;


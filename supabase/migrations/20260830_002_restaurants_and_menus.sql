      with check (
        exists (
          select 1 from public.profiles p
          where p.user_id = auth.uid() and p.role = 'admin'
        )
      );
  end if;
end
$$;

create index if not exists idx_menu_categories_restaurant
  on public.restaurant_menu_categories (restaurant_id, sort_order);

grant select, insert, update, delete on public.restaurant_menu_categories to authenticated;

-- ============================================================
-- C. Restaurant menu items
-- ============================================================

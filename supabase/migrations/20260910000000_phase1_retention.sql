-- I. Hardened SECURITY DEFINER RPC functions
-- All functions:
--   * SET search_path = '' to prevent search-path injection
--   * schema-qualify every table reference
--   * run with SECURITY DEFINER so RLS is bypassed in a controlled way
--   * are narrowly granted to authenticated only (not public/anon)
-- ============================================================

-- I.1 Provider reputation (read-only, calculated from REAL data only)
create or replace function public.get_provider_reputation(p_provider_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_total bigint;
  v_completed bigint;
  v_cancelled bigint;
  v_declined bigint;
  v_avg_rating numeric;
  v_review_count bigint;
  v_favorites_count bigint;
begin
  select count(*) into v_total
    from public.bookings b
   where b.provider_user_id = p_provider_user_id;

  select count(*) into v_completed
    from public.bookings b
   where b.provider_user_id = p_provider_user_id
     and lower(coalesce(b.status, '')) = 'completed';

  select count(*) into v_cancelled
    from public.bookings b
   where b.provider_user_id = p_provider_user_id
     and lower(coalesce(b.status, '')) = 'cancelled';

  select count(*) into v_declined
    from public.bookings b
   where b.provider_user_id = p_provider_user_id
     and lower(coalesce(b.status, '')) = 'declined';

  select coalesce(avg(r.rating), 0) into v_avg_rating
    from public.reviews r
   where r.provider_user_id = p_provider_user_id;

  select count(*) into v_review_count
    from public.reviews r
   where r.provider_user_id = p_provider_user_id;

  select count(*) into v_favorites_count
    from public.favorites f
   where f.provider_user_id = p_provider_user_id;

  return jsonb_build_object(
    'provider_user_id', p_provider_user_id,
    'total_bookings', coalesce(v_total, 0),
    'completed_bookings', coalesce(v_completed, 0),
    'cancelled_bookings', coalesce(v_cancelled, 0),
    'declined_bookings', coalesce(v_declined, 0),
    'review_count', coalesce(v_review_count, 0),
    'average_rating', round(coalesce(v_avg_rating, 0)::numeric, 1),
    'favorite_count', coalesce(v_favorites_count, 0)
  );
end;
$$;

-- I.2 Customer rewards (read-only lookup)
create or replace function public.get_customer_rewards(p_customer_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.customer_rewards%rowtype;
begin
  select * into v_row
    from public.customer_rewards cr
   where cr.customer_user_id = p_customer_user_id;

  if not found then
    return jsonb_build_object(
      'customer_user_id', p_customer_user_id,
      'points_balance', 0,
      'lifetime_points', 0
    );
  end if;

  return jsonb_build_object(
    'customer_user_id', v_row.customer_user_id,
    'points_balance', coalesce(v_row.points_balance, 0),
    'lifetime_points', coalesce(v_row.lifetime_points, 0)
  );
end;
$$;

-- I.3 Adjust customer points (mutation, restricted to server-side callers only)
-- SECURITY: This function is NOT granted to authenticated users.
-- Only the service_role (and future server-side triggers) may execute it.
create or replace function public.adjust_customer_points(
  p_customer_user_id uuid,
  p_points_delta integer,
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.customer_rewards%rowtype;
  v_new_balance integer;
  v_new_lifetime integer;
begin
  if p_points_delta is null then
    raise exception 'points_delta is required';
  end if;

  insert into public.customer_rewards (customer_user_id, points_balance, lifetime_points, updated_at)
  values (p_customer_user_id, 0, 0, now())
  on conflict (customer_user_id) do nothing;

  select * into v_row
    from public.customer_rewards cr
   where cr.customer_user_id = p_customer_user_id
   for update;

  v_new_balance := coalesce(v_row.points_balance, 0) + p_points_delta;
  v_new_lifetime := coalesce(v_row.lifetime_points, 0) + p_points_delta;

  update public.customer_rewards cr
     set points_balance = case when v_new_lifetime >= 0 then greatest(v_new_balance, 0) else v_new_balance end,
         lifetime_points = v_new_lifetime,
         updated_at = now()
   where cr.customer_user_id = p_customer_user_id;

  select * into v_row
    from public.customer_rewards cr
   where cr.customer_user_id = p_customer_user_id;

  insert into public.customer_reward_transactions (
    customer_user_id,
    points_delta,
    balance_after,
    reason,
    created_by,
    created_at
  ) values (
    p_customer_user_id,
    p_points_delta,
    coalesce(v_row.points_balance, 0),
    p_reason,
    null,
    now()
  );

  return jsonb_build_object(
    'customer_user_id', p_customer_user_id,
    'points_balance', coalesce(v_row.points_balance, 0),
    'lifetime_points', coalesce(v_row.lifetime_points, 0)
  );
end;
$$;

-- ============================================================
-- J. Function execution grants and revokes
-- ============================================================
-- These functions are SECURITY DEFINER. By default Postgres grants
-- EXECUTE to PUBLIC. We explicitly revoke from public/anon and grant
-- only to the roles that genuinely need them.

revoke execute on function public.get_provider_reputation(uuid) from public;
revoke execute on function public.get_provider_reputation(uuid) from anon;
grant execute on function public.get_provider_reputation(uuid) to authenticated;

revoke execute on function public.get_customer_rewards(uuid) from public;
revoke execute on function public.get_customer_rewards(uuid) from anon;
grant execute on function public.get_customer_rewards(uuid) to authenticated;

-- adjust_customer_points is intentionally NOT granted to authenticated.
-- Only service_role may execute it (service_role bypasses GRANT checks).
revoke execute on function public.adjust_customer_points(uuid, integer, text) from public;
revoke execute on function public.adjust_customer_points(uuid, integer, text) from anon;
revoke execute on function public.adjust_customer_points(uuid, integer, text) from authenticated;
grant execute on function public.adjust_customer_points(uuid, integer, text) to service_role;
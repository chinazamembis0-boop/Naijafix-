-- D. RLS policies for customer_rewards
-- ============================================================
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'customer_rewards'
      and policyname = 'Customers can view their own rewards'
  ) then
    create policy "Customers can view their own rewards"
      on public.customer_rewards for select to authenticated
      using (customer_user_id = auth.uid());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'customer_rewards'
      and policyname = 'Admins can manage customer rewards'
  ) then
    create policy "Admins can manage customer rewards"
      on public.customer_rewards for all to authenticated
      using (exists (select 1 from public.profiles p where p.user_id = auth.uid() and p.role = 'admin'))
      with check (exists (select 1 from public.profiles p where p.user_id = auth.uid() and p.role = 'admin'));
  end if;
end
$$;


-- NaijaFix Phase 1 marketplace retention and trust foundation.
-- Safe, idempotent migration.
-- Does NOT drop tables, delete data, reset the database, or overwrite existing rows.

-- ============================================================
-- A. Customer rewards foundation
-- ============================================================
create table if not exists public.customer_rewards (
  id bigint generated by default as identity primary key,
  customer_user_id uuid not null references public.profiles(user_id) on delete cascade,
  points_balance integer not null default 0,
  lifetime_points integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (customer_user_id)
);

alter table public.customer_rewards enable row level security;

create table if not exists public.customer_reward_transactions (
  id bigint generated by default as identity primary key,
  customer_user_id uuid not null references public.profiles(user_id) on delete cascade,
  points_delta integer not null,
  balance_after integer not null,
  reason text,
  created_by uuid,
  created_at timestamptz not null default now()
);

alter table public.customer_reward_transactions enable row level security;

-- ============================================================
-- B. Marketplace configuration (commission foundation only)
-- ============================================================
create table if not exists public.marketplace_settings (
  id integer primary key check (id = 1),
  service_commission_percent numeric(5, 2) not null default 0,
  restaurant_commission_percent numeric(5, 2) not null default 0,
  delivery_margin_percent numeric(5, 2) not null default 0,
  updated_at timestamptz not null default now()
);

insert into public.marketplace_settings (id, service_commission_percent, restaurant_commission_percent, delivery_margin_percent)
values (1, 0, 0, 0)
on conflict (id) do nothing;

alter table public.marketplace_settings enable row level security;


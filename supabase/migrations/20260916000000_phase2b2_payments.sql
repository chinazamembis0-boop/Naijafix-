-- NaijaFix Phase 2B-2 Step 1: protected marketplace payments database foundation.

-- Additive only. No destructive operations. No existing tables, columns,
-- policies, or functions are dropped, renamed, or repurposed.

-- The existing bookings payment scaffolding columns
-- (payment_status, payment_authorized_at, payment_completed_at,
-- payment_failed_at, refund_pending_at, refunded_at) are intentionally left
-- untouched. They remain available as a denormalized read cache for the
-- existing admin queries and are NOT modified by this migration.

-- This migration creates:
--   1. public.payments - the authoritative payment ledger
--   2. RLS policies for public.payments
--   3. SECURITY DEFINER RPC foundation functions

-- No Paystack integration, no webhook handling, no payout/transfer logic,
-- and no frontend changes are included in this step. The RPCs below are
-- database-state machines only; they do not call any external payment API.

-- PAYMENT STATE MACHINE (enforced by the RPCs below):
--   unpaid   -> pending   (customer initiates)
--   pending  -> authorized (external capture confirmed)
--   pending  -> failed    (external capture failed)
--   failed   -> pending   (retry)
--   authorized -> captured (settlement recorded)
--   authorized -> released  (booking completed)
--   authorized -> refunded  (pre-completion refund)
--   released   -> refunded  (post-completion refund)

-- No other transition is permitted. A caller may never supply an arbitrary
-- status; every transition is validated inside the SECURITY DEFINER body.



-- ============================================================
-- A. public.payments - authoritative payment ledger
-- ============================================================
-- One row per payment attempt. booking_id is the FK to bookings(id);
-- customer_user_id and provider_user_id are denormalized from the
-- booking row so RLS can filter without a join back to bookings.
-- paystack_reference is UNIQUE so a duplicate webhook/confirm can never
-- insert a second row for the same payment.
-- idempotency_key is UNIQUE so a customer cannot submit two initiates
-- for the same logical payment attempt.
create table if not exists public.payments (
  id                    bigint generated by default as identity primary key,
  booking_id            bigint not null references public.bookings(id) on delete cascade,
  customer_user_id      uuid not null,
  provider_user_id      uuid,
  amount                numeric(12,2) not null check (amount > 0),
  currency              char(3) not null default 'NGN',
  paystack_reference    text,
  paystack_access_code  text,
  status                text not null default 'unpaid'
                          check (status in (
                            'unpaid', 'pending', 'authorized',
                            'captured', 'released', 'failed', 'refunded'
                          )),
  idempotency_key       text,
  commission_percent    numeric(5,2),
  provider_payout       numeric(12,2),
  platform_fee          numeric(12,2),
  authorized_at         timestamptz,
  captured_at           timestamptz,
  released_at           timestamptz,
  refunded_at           timestamptz,
  metadata              jsonb,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

-- paystack_reference is unique when present (NULL allowed pre-init).
create unique index if not exists payments_paystack_reference_key
  on public.payments (paystack_reference)
  where paystack_reference is not null;

-- idempotency_key is unique when present (NULL allowed pre-init).
create unique index if not exists payments_idempotency_key_key
  on public.payments (idempotency_key)
  where idempotency_key is not null;

create index if not exists idx_payments_booking
  on public.payments (booking_id);

create index if not exists idx_payments_customer
  on public.payments (customer_user_id);

create index if not exists idx_payments_provider
  on public.payments (provider_user_id);

create index if not exists idx_payments_status
  on public.payments (status);



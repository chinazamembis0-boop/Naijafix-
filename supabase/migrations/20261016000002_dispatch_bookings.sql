-- Ewizzy: Direct Dispatch Booking (Motorcycle / Okada parcel delivery)
-- Additive only. No existing tables, columns, policies, or functions are
-- dropped, renamed, or repurposed. No payment gateway integration.
--
-- Schema:
--   public.dispatch_bookings - customer parcel delivery requests
--
-- Status machine:
--   pending           (created, awaiting rider assignment)
--   searching_for_rider (dispatched to rider queue)
--   accepted          (rider accepted, not yet picked up)
--   picked_up         (rider has the parcel)
--   in_transit        (rider en route to drop-off)
--   delivered         (terminal)
--   cancelled         (terminal, customer-only before acceptance)
--
-- Atomic claiming is enforced by a single conditional UPDATE in
-- claim_dispatch_booking(): exactly one concurrent caller can win.

-- ============================================================
-- A. public.dispatch_bookings
-- ============================================================
create table if not exists public.dispatch_bookings (
  id bigint generated by default as identity primary key,
  customer_user_id uuid not null,
  pickup_contact_name text not null,
  pickup_contact_phone text not null,
  pickup_address text not null,
  pickup_area text not null,
  recipient_name text not null,
  recipient_phone text not null,
  dropoff_address text not null,
  dropoff_area text not null,
  item_description text not null,
  package_details text,
  additional_instructions text,
  fare_estimate numeric(10, 2),
  rider_id bigint references public.riders(id) on delete set null,
  status text not null default 'pending'
    check (status in (
      'pending', 'searching_for_rider', 'accepted', 'picked_up',
      'in_transit', 'delivered', 'cancelled'
    )),
  accepted_at timestamptz,
  picked_up_at timestamptz,
  delivered_at timestamptz,
  cancelled_at timestamptz,
  cancelled_by uuid,
  cancel_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.dispatch_bookings enable row level security;

-- ============================================================
-- B. RLS policies for dispatch_bookings
-- ============================================================
do $$
begin
  -- Customers can view their own bookings
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'dispatch_bookings'
      and policyname = 'Customers can view their own dispatch bookings'
  ) then
    create policy "Customers can view their own dispatch bookings"
      on public.dispatch_bookings
      for select to authenticated
      using (customer_user_id = auth.uid());
  end if;

  -- Customers can create their own bookings
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'dispatch_bookings'
      and policyname = 'Customers can create their own dispatch bookings'
  ) then
    create policy "Customers can create their own dispatch bookings"
      on public.dispatch_bookings
      for insert to authenticated
      with check (customer_user_id = auth.uid());
  end if;

  -- Customers can cancel their own bookings (before acceptance)
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'dispatch_bookings'
      and policyname = 'Customers can cancel their own dispatch bookings'
  ) then
    create policy "Customers can cancel their own dispatch bookings"
      on public.dispatch_bookings
      for update to authenticated
      using (
        customer_user_id = auth.uid()
        and status in ('pending', 'searching_for_rider')
        and rider_id is null
      )
      with check (
        customer_user_id = auth.uid()
        and status = 'cancelled'
      );
  end if;

  -- Riders can view available dispatch bookings (pending, no rider assigned)
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'dispatch_bookings'
      and policyname = 'Riders can view available dispatch bookings'
  ) then
    create policy "Riders can view available dispatch bookings"
      on public.dispatch_bookings
      for select to authenticated
      using (
        status in ('pending', 'searching_for_rider')
        and rider_id is null
        and exists (
          select 1 from public.riders r
          where r.user_id = auth.uid()
            and r.active = true
            and r.available = true
        )
      );
  end if;

  -- Riders can view their own accepted/in-progress dispatch bookings
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'dispatch_bookings'
      and policyname = 'Riders can view their own dispatch bookings'
  ) then
    create policy "Riders can view their own dispatch bookings"
      on public.dispatch_bookings
      for select to authenticated
      using (
        rider_id is not null
        and rider_id = (select public.current_rider_id())
      );
  end if;

  -- Riders can update their own dispatch booking status (fulfilment fields only)
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'dispatch_bookings'
      and policyname = 'Riders can update their own dispatch bookings'
  ) then
    create policy "Riders can update their own dispatch bookings"
      on public.dispatch_bookings
      for update to authenticated
      using (
        rider_id is not null
        and rider_id = (select public.current_rider_id())
        and status <> 'delivered'
        and status <> 'cancelled'
      )
      with check (
        rider_id = (select public.current_rider_id())
      );
  end if;

  -- Restaurants cannot access dispatch bookings (no policy = no access)
  -- Admins can manage all dispatch bookings
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'dispatch_bookings'
      and policyname = 'Admins can manage all dispatch bookings'
  ) then
    create policy "Admins can manage all dispatch bookings"
      on public.dispatch_bookings
      for all to authenticated
      using (
        exists (
          select 1 from public.profiles p
          where p.user_id = auth.uid() and p.role = 'admin'
        )
      )
      with check (
        exists (
          select 1 from public.profiles p
          where p.user_id = auth.uid() and p.role = 'admin'
        )
      );
  end if;
end
$$;

-- Indexes
create index if not exists idx_dispatch_bookings_customer
  on public.dispatch_bookings (customer_user_id, created_at desc);

create index if not exists idx_dispatch_bookings_status
  on public.dispatch_bookings (status, created_at desc);

create index if not exists idx_dispatch_bookings_rider
  on public.dispatch_bookings (rider_id, created_at desc);

create index if not exists idx_dispatch_bookings_claimable
  on public.dispatch_bookings (created_at)
  where status in ('pending', 'searching_for_rider')
    and rider_id is null;

-- Table-level grants
grant select, insert, update on public.dispatch_bookings to authenticated;

-- ============================================================
-- C. claim_dispatch_booking RPC (atomic, race-safe claiming)
-- ============================================================
create or replace function public.claim_dispatch_booking(p_booking_id bigint)
returns public.dispatch_bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_rider public.riders%rowtype;
  v_booking public.dispatch_bookings%rowtype;
begin
  if p_booking_id is null then
    raise exception 'booking_id is required' using errcode = '22023';
  end if;

  select r.*
    into v_rider
    from public.riders r
   where r.user_id = auth.uid()
     and r.active = true
   limit 1;

  if not found then
    raise exception 'You are not an active Ewizzy rider' using errcode = '42501';
  end if;

  if not v_rider.available then
    raise exception 'Go online before accepting a dispatch' using errcode = '42501';
  end if;

  -- Atomic conditional claim. Exactly one concurrent caller can win.
  update public.dispatch_bookings o
     set rider_id = v_rider.id,
         status = 'accepted',
         accepted_at = now(),
         updated_at = now()
   where o.id = p_booking_id
     and o.status in ('pending', 'searching_for_rider')
     and o.rider_id is null
  returning * into v_booking;

  if not found then
    raise exception
      'This dispatch booking is no longer available. It was just taken by another rider.'
      using errcode = 'P0001';
  end if;

  return v_booking;
end;
$$;

revoke execute on function public.claim_dispatch_booking(bigint) from public;
revoke execute on function public.claim_dispatch_booking(bigint) from anon;
grant execute on function public.claim_dispatch_booking(bigint) to authenticated;

comment on function public.claim_dispatch_booking(bigint) is
  'Atomically assigns an unclaimed pending/searching dispatch booking to the current rider.';

-- ============================================================
-- D. BEFORE UPDATE guard for dispatch_bookings
-- ============================================================
create or replace function public.dispatch_bookings_guard_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_is_admin boolean := false;
  v_is_customer boolean := false;
  v_is_assigned_rider boolean := false;
begin
  -- Only enforce when a real user is making the call
  if v_uid is null then
    return new;
  end if;

  -- Resolve admin status
  if exists (
    select 1 from public.profiles p
    where p.user_id = v_uid and p.role = 'admin'
  ) then
    v_is_admin := true;
  end if;

  -- Resolve customer status
  if old.customer_user_id = v_uid then
    v_is_customer := true;
  end if;

  -- Resolve assigned rider status
  if not v_is_admin
     and old.rider_id is not null
     and old.rider_id = (select public.current_rider_id()) then
    v_is_assigned_rider := true;
  end if;

  -- Status transition guard
  if new.status is distinct from old.status then
    if not v_is_admin then
      if not public.dispatch_booking_transition_allowed(old.status, new.status) then
        raise exception
          'Illegal dispatch booking status transition: % -> %', old.status, new.status
          using errcode = '22023';
      end if;

      -- Only customer, admin can cancel
      if new.status = 'cancelled'
         and not (v_is_admin or v_is_customer) then
        raise exception
          'Only the customer or an admin may cancel a dispatch booking'
          using errcode = '42501';
      end if;
    end if;
  end if;

  -- Assigned rider may only change status (fulfilment), not customer/address/etc.
  if v_is_assigned_rider and not v_is_admin then
    if new.customer_user_id   is distinct from old.customer_user_id
       or new.pickup_contact_name   is distinct from old.pickup_contact_name
       or new.pickup_contact_phone  is distinct from old.pickup_contact_phone
       or new.pickup_address        is distinct from old.pickup_address
       or new.pickup_area           is distinct from old.pickup_area
       or new.recipient_name        is distinct from old.recipient_name
       or new.recipient_phone       is distinct from old.recipient_phone
       or new.dropoff_address       is distinct from old.dropoff_address
       or new.dropoff_area          is distinct from old.dropoff_area
       or new.item_description      is distinct from old.item_description
       or new.package_details       is distinct from old.package_details
       or new.additional_instructions is distinct from old.additional_instructions
       or new.fare_estimate         is distinct from old.fare_estimate
       or new.rider_id              is distinct from old.rider_id then
      raise exception
        'Riders may not modify protected dispatch booking fields'
        using errcode = '42501';
    end if;
  end if;

  -- Terminal timestamps managed by server
  if new.status is distinct from old.status then
    if new.status = 'accepted' and old.accepted_at is null then
      new.accepted_at := now();
    end if;
    if new.status = 'picked_up' and old.picked_up_at is null then
      new.picked_up_at := now();
    end if;
    if new.status = 'delivered' and old.delivered_at is null then
      new.delivered_at := now();
    end if;
    if new.status = 'cancelled' then
      new.cancelled_at := now();
      new.cancelled_by := v_uid;
    else
      new.cancelled_at := null;
      new.cancelled_by := null;
    end if;
  elsif new.status = 'cancelled' then
    new.cancelled_at := old.cancelled_at;
    new.cancelled_by := old.cancelled_by;
  end if;

  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists dispatch_bookings_guard_update on public.dispatch_bookings;
create trigger dispatch_bookings_guard_update
  before update on public.dispatch_bookings
  for each row
  execute function public.dispatch_bookings_guard_update();

-- ============================================================
-- E. dispatch_booking_transition_allowed predicate
-- ============================================================
create or replace function public.dispatch_booking_transition_allowed(
  p_from text,
  p_to   text
)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select case
    when p_from is null or p_to is null then false
    when p_from = p_to then true
    when p_to = 'cancelled' then
      p_from in ('pending', 'searching_for_rider')
    when p_from = 'pending'           and p_to = 'searching_for_rider' then true
    when p_from = 'searching_for_rider' and p_to = 'accepted' then true
    when p_from = 'accepted'          and p_to = 'picked_up' then true
    when p_from = 'picked_up'         and p_to = 'in_transit' then true
    when p_from = 'in_transit'        and p_to = 'delivered' then true
    else false
  end;
$$;

revoke execute on function public.dispatch_booking_transition_allowed(text, text) from public;
revoke execute on function public.dispatch_booking_transition_allowed(text, text) from anon;
grant execute on function public.dispatch_booking_transition_allowed(text, text) to authenticated;

comment on function public.dispatch_booking_transition_allowed(text, text) is
  'True when a dispatch booking may move from p_from to p_to.';
